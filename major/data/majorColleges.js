function getCollegeForMajor(major) {
    return MAJOR_COLLEGE_MAP[major] || UNCLASSIFIED_COLLEGE;
}

function getMajorsByCollege(majors, college) {
    return majors.filter((major) => getCollegeForMajor(major) === college);
}

